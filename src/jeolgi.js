/**
 * 절기일 계산 (Shouxi 만년력 알고리즘)
 * @param {number} year  - 양력 연도
 * @param {number} monthIdx - 월 인덱스 (0=1월/소한, 1=2월/입춘, ..., 11=12월/대설)
 * @returns {number} 해당 월의 절기 일(day)
 */
export function getJeolgiDay(year, monthIdx) {
  // 1. 검증 테이블에 있으면 바로 반환 (가장 정확)
  if (VERIFIED[year]) {
    return VERIFIED[year][monthIdx];
  }

  // 2. Shouxi 알고리즘으로 계산
  const is21c = year >= 2000;
  const Y = is21c ? year - 2000 : year - 1900;
  const C = is21c ? C21[monthIdx] : C20[monthIdx];

  // 윤년 보정: 1~2월은 (Y-1)/4, 3~12월은 Y/4
  const L = monthIdx <= 1 ? Math.floor((Y - 1) / 4) : Math.floor(Y / 4);

  let day = Math.floor(Y * 0.2422 + C) - L;

  // 3. 예외 보정 적용
  const key = `${year}_${monthIdx}`;
  if (CORRECTIONS[key]) {
    day += CORRECTIONS[key];
  }

  return day;
}

/**
 * 특정 연도의 12절기 일자 배열 반환
 * @param {number} year - 양력 연도
 * @returns {number[]} [소한일, 입춘일, 경칩일, ..., 대설일]
 */
export function getYearJeolgi(year) {
  return Array.from({ length: 12 }, (_, i) => getJeolgiDay(year, i));
}

