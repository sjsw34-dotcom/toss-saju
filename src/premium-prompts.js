/**
 * 프리미엄 항목 제목에 매칭되는 카테고리 프롬프트 반환
 * @param {string} itemTitle - premiumItems의 title
 * @returns {{ systemExtra: string, promptExtra: string }}
 */
export function getCategoryPrompt(itemTitle) {
  const t = itemTitle;
  if (t.includes("애정") || t.includes("연애") || t.includes("사랑")) return CATEGORY_PROMPTS["애정운"];
  if (t.includes("말년") || t.includes("노후")) return CATEGORY_PROMPTS["말년운세"];
  if (t.includes("갱년기") || t.includes("건강")) return CATEGORY_PROMPTS["건강운"];
  if (t.includes("횡재") || t.includes("로또") || t.includes("투자")) return CATEGORY_PROMPTS["횡재수"];
  if (t.includes("삼재") || t.includes("액운")) return CATEGORY_PROMPTS["삼재액운"];
  if (t.includes("황금기") || t.includes("인생")) return CATEGORY_PROMPTS["황금기"];
  if (t.includes("은퇴")) return CATEGORY_PROMPTS["은퇴후"];
  if (t.includes("직업") || t.includes("전직") || t.includes("부업")) return CATEGORY_PROMPTS["직업전환"];
  if (t.includes("가족") || t.includes("갈등")) return CATEGORY_PROMPTS["가족관계"];
  if (t.includes("창업") || t.includes("가게")) return CATEGORY_PROMPTS["창업운"];
  if (t.includes("이사") || t.includes("매매") || t.includes("부동산")) return CATEGORY_PROMPTS["이사매매"];
  // 매칭 실패 시 기본값
  return { systemExtra: "", promptExtra: "" };
}

